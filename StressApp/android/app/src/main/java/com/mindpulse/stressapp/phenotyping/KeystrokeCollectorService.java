    // -----------------------------------------------------------------------
    // T7-A: Activity Recognition — noise gate
    // -----------------------------------------------------------------------
    private static final String ACTION_ACTIVITY_UPDATE =
        "com.mindpulse.stressapp.phenotyping.ACTIVITY_UPDATE";

    private static final int[] NOISY_ACTIVITIES = {
        DetectedActivity.WALKING,
        DetectedActivity.RUNNING,
        DetectedActivity.ON_BICYCLE,
        DetectedActivity.IN_VEHICLE,
        DetectedActivity.ON_FOOT,
    };

    private static final int ACTIVITY_CONFIDENCE_THRESHOLD = 60;
    private static final long ACTIVITY_POLL_MS = UPLOAD_INTERVAL_MS;

    private ActivityRecognitionClient activityRecognitionClient;
    private PendingIntent             activityPendingIntent;

    private volatile boolean dataValid = true;   // true = user is stationary/still

    private final BroadcastReceiver activityReceiver = new BroadcastReceiver() {
        @Override
        public void onReceive(Context context, Intent intent) {
            if (!ACTION_ACTIVITY_UPDATE.equals(intent.getAction())) return;
            if (!ActivityRecognitionResult.hasResult(intent)) return;

            ActivityRecognitionResult result = ActivityRecognitionResult.extractResult(intent);
            if (result == null) return;

            DetectedActivity mostLikely = result.getMostProbableActivity();
            int type       = mostLikely.getType();
            int confidence = mostLikely.getConfidence();

            boolean isNoisy = false;
            for (int noisy : NOISY_ACTIVITIES) {
                if (type == noisy && confidence >= ACTIVITY_CONFIDENCE_THRESHOLD) {
                    isNoisy = true;
                    break;
                }
            }

            dataValid = !isNoisy;

            Log.d(TAG, "Activity: " + activityName(type)
                + " (" + confidence + "%) -> data_valid=" + dataValid);
        }
    };

    // -----------------------------------------------------------------------
    // State — inter-keystroke intervals (proxy for flight time)
    // -----------------------------------------------------------------------
    private final List<Long> flightTimes  = new ArrayList<>();
    private final List<Long> dwellTimes   = new ArrayList<>();
    private final List<Long> scrollSpeeds = new ArrayList<>();

    private long   scrollGesturePxSum    = 0;
    private long   scrollGestureStartMs  = 0;
    private long   lastScrollEventMs     = 0;
    private static final long SCROLL_GESTURE_GAP_MS = 300;

    // -----------------------------------------------------------------------
    // Tilt angle — measured from accelerometer via low-pass gravity filter
    // -----------------------------------------------------------------------
    private SensorManager sensorManager;
    private final float[] gravityFilter  = new float[3];  // low-pass gravity estimate
    private final float   ALPHA_GRAVITY  = 0.8f;          // low-pass smoothing constant
    private volatile double currentTiltAngle = 0.0;       // degrees; updated in real-time

    private final SensorEventListener tiltListener = new SensorEventListener() {
        @Override
        public void onSensorChanged(SensorEvent event) {
            // Low-pass filter to isolate gravity component from linear acceleration noise
            gravityFilter[0] = ALPHA_GRAVITY * gravityFilter[0] + (1 - ALPHA_GRAVITY) * event.values[0];
            gravityFilter[1] = ALPHA_GRAVITY * gravityFilter[1] + (1 - ALPHA_GRAVITY) * event.values[1];
            gravityFilter[2] = ALPHA_GRAVITY * gravityFilter[2] + (1 - ALPHA_GRAVITY) * event.values[2];
            // Tilt angle: angle between the device Y-axis and the gravity vector
            // Result in degrees: 0 = flat on table, 90 = held upright, 180 = upside-down
            double tiltRad = Math.atan2(
                Math.sqrt(gravityFilter[0] * gravityFilter[0] + gravityFilter[2] * gravityFilter[2]),
                gravityFilter[1]
            );
            currentTiltAngle = Math.toDegrees(tiltRad);
        }

        @Override
        public void onAccuracyChanged(Sensor sensor, int accuracy) { /* not used */ }
    };

    private long   lastFocusEventTime = 0;
    private static final long MAX_FOCUS_PAIR_MS = 500;

    private long   lastKeyPressTime = 0;
    private int    unlockCount      = 0;
    private int    appSwitchCount   = 0;
    private String lastPackageName  = "";
    private long   sessionStartTime = System.currentTimeMillis();

    private int consecutiveIdentityFailures = 0;
    private static final int MAX_IDENTITY_FAILURES_BEFORE_DROP = 20;

    private final Handler handler = new Handler(Looper.getMainLooper());

